import { compositeScore, hygienePenalties, judgeScore, mean, round, weights, type JudgeVerdict } from "./composite.ts";
import { judgeLabels } from "./judge.ts";
import type { ArmScore, TaskScores } from "./score-task.ts";
import type { Task } from "./task.ts";

export type Judgement = { model: string; verdicts: Record<string, JudgeVerdict> };
export type TaskReport = { task: Task; scores: TaskScores; judgement?: Judgement };

type Row = { run: string; arm: string; score: ArmScore; verdict?: JudgeVerdict; judge: number | null; composite: number | null };

const missing = "–";

export function renderReport(reports: TaskReport[]): string {
  const rows = reports.map((report) => ({ report, rows: rowsOf(report) }));
  return [
    "# Benchmark: does architecture planning change how an agent builds?",
    "Generated by `bun benchmark/report.ts` from `benchmark/runs/`. Each task replays one of Michael's PostHog pull requests from the base commit its author started on. See issue #61 for the design.",
    method(),
    "## Results per task",
    ...rows.map(({ report, rows }) => taskSection(report, rows)),
    armMeans(rows.flatMap(({ rows }) => rows)),
    spread(rows),
    caveats(),
  ].join("\n\n");
}

function rowsOf({ scores, judgement }: TaskReport): Row[] {
  return Object.entries(scores.arms).map(([run, score]) => {
    const verdict = judgement?.verdicts[run];
    const judge = verdict ? judgeScore(verdict) : null;
    const composite = judge !== null && score.hygiene !== null && score.focusScore !== null ? compositeScore({ hygiene: score.hygiene, judge, focus: score.focusScore }) : null;
    return { run, arm: score.arm, score, verdict, judge, composite };
  });
}

function method(): string {
  return [
    "## Method",
    "- **Arm A, original:** the merged PR's own diff (`git diff base...finalHead`), with a human steering its authoring session over many turns.",
    "- **Arm B, replay without the tool:** Claude Opus 5.5 (`claude-opus-5-5`, gateway bypassed) gets the task statement verbatim and is told to implement it without committing. No MCP servers.",
    "- **Arm C, replay with the tool:** the same model and prompt, plus the uml-pr-review MCP server, the `planning-architecture` skill as appended system prompt, and standing approval to lock its own plan.",
    "",
    `**Composite architecture score (0–100)** = ${pct(weights.hygiene)} boundary hygiene + ${pct(weights.judge)} judge + ${pct(weights.focus)} focus. Every sub-score is shown next to it.`,
    "",
    "- **Boundary hygiene** starts at 100 and loses points for each new import the diff introduces, measured by indexing the base tree and the patched tree with this repository's architecture indexer, and applying PostHog's own rules (`products/architecture.md`, `tach.toml`):",
    `  - facade bypass, an import from outside \`products/<p>/\` into \`products/<p>/backend/**\` other than \`backend/facade/**\` or \`backend/routes.py\`: −${hygienePenalties.facadeBypass} (imports from test files are listed but not penalized; frontend imports are outside the rule);`,
    `  - new dependency between tach modules that is not declared in the patched \`tach.toml\`: −${hygienePenalties.undeclaredDependency}; declared: −${hygienePenalties.declaredDependency};`,
    `  - new tach-module cycle (two modules that become mutually dependent): −${hygienePenalties.newCycle};`,
    `  - new unresolved import in a changed file: −${hygienePenalties.unresolvedImport}.`,
    "- **Focus** compares arms of the same task: for modules touched, new cross-module edges, and lines changed, each arm scores (best + 1) / (own + 1), averaged, × 100. The tightest arm on every measure scores 100. Tests added are shown but not scored.",
    `- **Judge** is the mean of the four architecture dimensions (seams, cohesion, coupling, fit) × 10, from one blind \`codex exec -m gpt-6-astra\` call per task that sees the diffs under shuffled labels (${judgeLabels.slice(0, 3).join("/")}…), the task statement, and \`products/architecture.md\`. The overall score is shown but not used.`,
    "- **Build sanity:** `python3 -m py_compile` on changed Python files; `ruff check` when ruff is installed; TypeScript is not checked (PostHog's `tsc` is too slow per arm).",
    "- **Process** comes from the transcripts: tool calls and time before the first edit, architecture exploration before it (uml-pr-review tools, or reads of `architecture.md`, `tach.toml`, or a facade), and messages reasoning about modules, seams, or boundaries before it.",
  ].join("\n");
}

function taskSection({ task, scores, judgement }: TaskReport, rows: Row[]): string {
  const header = `### [#${task.pr}](${task.url ?? `https://github.com/PostHog/posthog/pull/${task.pr}`}) ${task.title}`;
  const context = `Base \`${scores.baseCommit.slice(0, 11)}\`. Judge: ${judgement ? `\`${judgement.model}\`` : "not run yet"}.`;
  return [header, context, scoreTable(rows), processTable(rows), excerpts(rows)].join("\n\n");
}

function scoreTable(rows: Row[]): string {
  const head = "| Run | Exit | Hygiene | Bypasses | New deps (undeclared) | Cycles | Unresolved | Files | Lines | Modules | Tests | Focus | Seams | Cohesion | Coupling | Fit | Overall | Judge | Composite |";
  const lines = rows.map(({ run, score, verdict, judge, composite }) => {
    const boundary = score.boundary;
    const focus = score.focus;
    const dependencies = boundary?.newCrossProductDependencies ?? [];
    return cells([
      run,
      score.exit?.reason ?? missing,
      score.hygiene ?? diffNote(score),
      boundary ? boundary.facadeBypasses.length : missing,
      boundary ? `${dependencies.length} (${dependencies.filter(({ declared }) => !declared).length})` : missing,
      boundary?.newCycles.length ?? missing,
      boundary?.newUnresolvedImports.length ?? missing,
      focus?.filesChanged ?? missing,
      focus ? focus.linesAdded + focus.linesRemoved : missing,
      focus?.modulesTouched ?? missing,
      focus?.testsAdded ?? missing,
      score.focusScore ?? missing,
      verdict?.seams.score ?? missing,
      verdict?.cohesion.score ?? missing,
      verdict?.coupling.score ?? missing,
      verdict?.fit.score ?? missing,
      verdict?.overall.score ?? missing,
      judge ?? missing,
      composite === null ? missing : `**${composite}**`,
    ]);
  });
  return [head, separator(head), ...lines].join("\n");
}

function processTable(rows: Row[]): string {
  const head = "| Run | Tool calls before first edit | Seconds before first edit | Architecture exploration before edit | Architecture reasoning before edit | Arch. tool calls | Turns | Wall (s) | Cost ($) | py_compile failures |";
  const lines = rows.map(({ run, score }) => {
    const process = score.process;
    return cells([
      run,
      process?.toolCallsBeforeFirstEdit ?? missing,
      process?.secondsBeforeFirstEdit ?? missing,
      process?.architectureExplorationBeforeEdit ?? missing,
      process?.architectureReasoningBeforeEdit ?? missing,
      process?.architectureToolCalls ?? missing,
      process?.turns ?? missing,
      process?.wallSeconds ?? missing,
      process?.costUsd === null || process?.costUsd === undefined ? missing : process.costUsd.toFixed(2),
      score.build ? score.build.pyCompileFailures.length : missing,
    ]);
  });
  return [head, separator(head), ...lines].join("\n");
}

function excerpts(rows: Row[]): string {
  const firsts = [...new Map(rows.map((row) => [row.arm, row])).values()].filter(({ score }) => score.process);
  if (firsts.length === 0) return "_No transcripts for this task._";
  return [
    "How the thinking differed before the first edit:",
    ...firsts.map(({ run, score }) => {
      const process = score.process!;
      const thought = process.firstArchitectureThought ? `first architecture thought: “${process.firstArchitectureThought.replaceAll("|", "\\|")}”` : "no architecture reasoning before it";
      return `- **${run}** made ${process.toolCallsBeforeFirstEdit} tool calls (${process.architectureExplorationBeforeEdit} architecture exploration) before its first edit; ${thought}`;
    }),
  ].join("\n");
}

function armMeans(rows: Row[]): string {
  const arms = [...new Set(rows.map(({ arm }) => arm))].sort();
  const head = "| Arm | Runs | Composite | Hygiene | Judge | Focus | Facade bypasses per run |";
  const lines = arms.map((arm) => {
    const own = rows.filter((row) => row.arm === arm);
    return cells([
      arm,
      own.length,
      meanOf(own.map(({ composite }) => composite)),
      meanOf(own.map(({ score }) => score.hygiene)),
      meanOf(own.map(({ judge }) => judge)),
      meanOf(own.map(({ score }) => score.focusScore)),
      meanOf(own.map(({ score }) => score.boundary?.facadeBypasses.length ?? null)),
    ]);
  });
  return ["## Per-arm means", "Means over every scored run of the arm, across tasks; a dash means no run of the arm has that score yet.", [head, separator(head), ...lines].join("\n")].join("\n\n");
}

function spread(tasks: { report: TaskReport; rows: Row[] }[]): string {
  const head = "| Task | Arm | Runs | Composite min–max | Hygiene min–max | Judge min–max |";
  const lines = tasks.flatMap(({ report, rows }) =>
    [...new Set(rows.map(({ arm }) => arm))]
      .map((arm) => rows.filter((row) => row.arm === arm))
      .filter((own) => own.length > 1)
      .map((own) => cells([`#${report.task.pr}`, own[0]!.arm, own.length, range(own.map(({ composite }) => composite)), range(own.map(({ score }) => score.hygiene)), range(own.map(({ judge }) => judge))])),
  );
  const body = lines.length > 0 ? [head, separator(head), ...lines].join("\n") : "_No task has repeated runs of an arm yet._";
  return ["## Spread over repeats", body].join("\n\n");
}

function caveats(): string {
  return [
    "## Honesty caveats",
    "- Arm A had a human steering it over many turns, with review feedback; arms B and C get the task statement only. A–B differences conflate the model, the time, and the steering. B–C is the controlled comparison.",
    "- Replays are stochastic. Where the budget allowed, B and C ran more than once, and the spread above shows how far one run can be from another. With few tasks and few repeats, small differences are noise.",
    "- The judge is one model call per task. It is blind to the arms but not free of bias, and its scores are a second opinion, not ground truth.",
    "- Boundary hygiene sees imports only. It does not see model access through `apps.get_model`, ORM traversal, or HTTP coupling, which `products/architecture.md` also governs.",
    "- Focus is relative within a task: it rewards the smallest change, which is not always the right one.",
    "- No arm's diff is committed anywhere. PostHog stays untouched apart from scratch worktrees, which are removed after each run.",
  ].join("\n");
}

function diffNote(score: ArmScore): string {
  return score.application === "empty" ? "no diff" : score.application === "failed" ? "diff did not apply" : missing;
}

function meanOf(values: (number | null)[]): string | number {
  const present = values.filter((value): value is number => value !== null);
  return present.length > 0 ? round(mean(present)) : missing;
}

function range(values: (number | null)[]): string {
  const present = values.filter((value): value is number => value !== null);
  return present.length > 0 ? `${Math.min(...present)}–${Math.max(...present)}` : missing;
}

function cells(values: (string | number)[]): string {
  return `| ${values.join(" | ")} |`;
}

function separator(head: string): string {
  return `|${head.split("|").slice(1, -1).map(() => "---").join("|")}|`;
}

function pct(weight: number): string {
  return `${Math.round(weight * 100)}%`;
}
