import { angleWeights, anglesOf, compositeOf, fullTestRatio, processTargets, staticPenalties, type Angle, type Angles } from "./angles.ts";
import type { JevReport } from "./jev.ts";
import { judgeLabels } from "./judge.ts";
import { hygienePenalties, mean, round, type JudgeVerdict } from "./metric-scores.ts";
import type { ArmScore, TaskScores } from "./score-task.ts";
import type { Task } from "./task.ts";

export type Judgement = { model: string; verdicts: Record<string, JudgeVerdict> };
export type TaskReport = { task: Task; scores: TaskScores; judgement?: Judgement; jev?: JevReport };

type Row = { run: string; arm: string; score: ArmScore; verdict?: JudgeVerdict; angles: Angles; composite: number | null };
type TaskRows = { report: TaskReport; rows: Row[] };

const missing = "–";
const angleColumns: [Angle, string][] = [
  ["architecture", "Architecture"],
  ["staticQuality", "Static quality"],
  ["tests", "Tests"],
  ["jev", "Jev"],
  ["astra", "Astra judge"],
  ["alignment", "Intent alignment"],
  ["process", "Process"],
];

export function renderReport(reports: TaskReport[]): string {
  const tasks = reports.map((report) => ({ report, rows: rowsOf(report) }));
  return [
    "# Benchmark: does architecture planning change how an agent builds?",
    "Generated by `bun benchmark/report.ts` from `benchmark/runs/`. Each task replays one of Michael's PostHog pull requests from the base commit its author started on. See issue #61 for the design.",
    method(),
    gradesTable(tasks),
    armMeans(tasks.flatMap(({ rows }) => rows)),
    consistencyTable(tasks),
    spread(tasks),
    "## Details per task",
    ...tasks.map(taskSection),
    caveats(),
  ].join("\n\n");
}

function rowsOf({ scores, judgement, jev }: TaskReport): Row[] {
  return Object.entries(scores.arms).map(([run, score]) => {
    const verdict = judgement?.verdicts[run];
    const angles = anglesOf({
      hygiene: score.hygiene,
      focusScore: score.focusScore,
      verdict,
      jev: jev?.status === "graded" ? jev.runs[run] : undefined,
      staticQuality: score.staticQuality,
      ruffFindings: score.build?.ruff.available && score.build.pythonFiles > 0 ? score.build.ruff.violations.length : null,
      tests: score.tests,
      alignment: score.alignment,
      process: score.process,
    });
    return { run, arm: score.arm, score, verdict, angles, composite: compositeOf(angles) };
  });
}

function method(): string {
  const weights = angleColumns.map(([angle, label]) => `${label} ${angleWeights[angle]}`).join(", ");
  return [
    "## Method",
    "- **Arm A, original:** the merged PR's own changes, diffed from the upstream commit its branch last synced with, with a human steering its authoring session over many turns.",
    "- **Arm B, replay without the tool:** Claude Opus 5.5 (`claude-opus-5-5`, gateway bypassed) gets the task statement verbatim and is told to implement it without committing. No MCP servers.",
    "- **Arm C, replay with the tool:** the same model and prompt, plus the uml-pr-review MCP server, the `planning-architecture` skill as appended system prompt, and standing approval to lock its own plan.",
    "",
    "Every angle is graded 0–100 on its own and shown next to the composite, so the composite hides nothing.",
    "",
    `**Composite** = the weighted mean of the angles a run has: ${weights}. An angle a run cannot have (intent alignment for arm A itself, Jev or the judge before they ran) is left out and the remaining weights are rescaled, never counted as zero. Consistency is a property of an arm across repeats, so it is reported beside the composite, not in it.`,
    "",
    "- **Architecture** = ⅔ boundary hygiene + ⅓ focus, both measured by indexing the base tree and the patched tree with this repository's architecture indexer and applying PostHog's own rules (`products/architecture.md`, `tach.toml`).",
    `  - Boundary hygiene starts at 100. A facade bypass (an import from outside \`products/<p>/\` into \`products/<p>/backend/**\` other than \`backend/facade/**\` or \`backend/routes.py\`) costs ${hygienePenalties.facadeBypass}; imports from test files are listed but not penalized, and frontend imports are outside the rule. A new tach-module dependency costs ${hygienePenalties.undeclaredDependency} when the patched \`tach.toml\` does not declare it and ${hygienePenalties.declaredDependency} when it does. A new tach-module cycle costs ${hygienePenalties.newCycle}. A new unresolved import in a changed file costs ${hygienePenalties.unresolvedImport}.`,
    "  - Focus compares the arms of one task: for modules touched, new cross-module edges, and lines changed, each run scores (best + 1) / (own + 1), averaged, × 100.",
    `- **Static quality** starts at 100. \`lizard\` measures every function in the changed \`.py\`, \`.ts\`, and \`.tsx\` files at the base and after the change; a function is new or changed when its signature is new or its tokens, NLOC, or complexity moved. Each changed function with cyclomatic complexity above 10 costs ${staticPenalties.complexFunction}, each point of mean complexity above 5 costs ${staticPenalties.meanCcnAboveFive}, each \`ruff\` finding on changed Python costs ${staticPenalties.ruffFinding}, and each percent of duplicated lines that \`jscpd\` finds across the changed files costs ${staticPenalties.duplicatedPercent}.`,
    `- **Tests** is the mean of: the test-to-production added-lines ratio (a ratio of ${fullTestRatio} or more earns full marks); reference coverage, the share of new or changed production functions and classes that a changed test file names; and, when it ran, whether \`pytest\` passed on the changed test files. \`pytest\` runs only when PostHog's services and Python environment are available; \`not run\` is left out, never counted as a failure.`,
    "- **Jev** is TypeSafe AI's deterministic evaluation model (`typesafe-ai/jev`, through the Vercel AI Gateway). Per changed production file (its hunks plus about 60 lines of context on each side, capped at 12,000 characters; the per-diff questions see the first 16,000 characters of the diff) it rates readability, single responsibility, naming clarity, error handling, and fit with the surrounding idioms; per changed test file, whether the tests assert behaviour and cover edge cases; per diff, whether the tests cover the new behaviour, whether the change stays on task, and how explicit the module interfaces are. Booleans count as their probability, scores as their level over the top level; the grade is the mean × 100. Answers are cached by input fingerprint, so re-grading is free and deterministic.",
    `- **Astra judge** is the mean of the four architecture dimensions (seams, cohesion, coupling, fit) × 10, from one blind \`codex exec -m gpt-6-astra\` call per task that sees every diff under shuffled labels (${judgeLabels.slice(0, 3).join("/")}…), the task statement, and \`products/architecture.md\`. Its overall score is shown but not used.`,
    "- **Intent alignment** is the mean of two Jaccard overlaps with arm A, the merged PR: of the modules touched (the first three folder levels of each changed file) and of the files touched.",
    `- **Process** comes from the transcripts: half for architecture exploration before the first edit (uml-pr-review tools, or reading \`architecture.md\`, \`tach.toml\`, or a facade; ${processTargets.exploration} calls earn full marks), half for messages reasoning about modules, seams, facades, or boundaries before it (${processTargets.reasoning} earn full marks).`,
    "- **Consistency** is the mean pairwise module and file Jaccard between repeated runs of the same arm on the same task.",
    "- **Build sanity** (`python3 -m py_compile` on changed Python) is reported in the details; TypeScript is not type-checked, because PostHog's `tsc` is too slow per arm.",
  ].join("\n");
}

function gradesTable(tasks: TaskRows[]): string {
  const head = `| Task | Run | Exit | ${angleColumns.map(([, label]) => label).join(" | ")} | Consistency | **Composite** |`;
  const lines = tasks.flatMap(({ report, rows }) =>
    rows.map((row) =>
      cells([
        `#${report.task.pr}`,
        row.run,
        row.score.exit?.reason ?? missing,
        ...angleColumns.map(([angle]) => row.angles[angle] ?? missing),
        consistencyCell(report.scores.consistency[row.arm]),
        row.composite === null ? missing : `**${row.composite}**`,
      ]),
    ),
  );
  return ["## Grades by angle", [head, separator(head), ...lines].join("\n")].join("\n\n");
}

function armMeans(rows: Row[]): string {
  const arms = [...new Set(rows.map(({ arm }) => arm))].sort();
  const head = `| Arm | Runs | ${angleColumns.map(([, label]) => label).join(" | ")} | **Composite** | Facade bypasses per run |`;
  const lines = arms.map((arm) => {
    const own = rows.filter((row) => row.arm === arm);
    return cells([
      arm,
      own.length,
      ...angleColumns.map(([angle]) => meanOf(own.map(({ angles }) => angles[angle]))),
      meanOf(own.map(({ composite }) => composite)),
      meanOf(own.map(({ score }) => score.boundary?.facadeBypasses.length ?? null)),
    ]);
  });
  return ["## Per-arm means", "Means over every graded run of the arm, across tasks; a dash means no run of the arm has that grade yet.", [head, separator(head), ...lines].join("\n")].join("\n\n");
}

function consistencyTable(tasks: TaskRows[]): string {
  const head = "| Task | Arm | Module Jaccard | File Jaccard |";
  const lines = tasks.flatMap(({ report }) =>
    Object.entries(report.scores.consistency)
      .filter(([, overlap]) => overlap !== null)
      .map(([arm, overlap]) => cells([`#${report.task.pr}`, arm, overlap!.modules, overlap!.files])),
  );
  const body = lines.length > 0 ? [head, separator(head), ...lines].join("\n") : "_No arm has repeated runs yet; run B and C with `--repeat 2`._";
  return ["## Consistency across repeats", "Is arm C more consistent than arm B? Higher overlap between repeats of one arm means the arm lands on the same modules and files each time.", body].join("\n\n");
}

function spread(tasks: TaskRows[]): string {
  const head = "| Task | Arm | Runs | Composite min–max | Architecture min–max | Astra min–max |";
  const lines = tasks.flatMap(({ report, rows }) =>
    [...new Set(rows.map(({ arm }) => arm))]
      .map((arm) => rows.filter((row) => row.arm === arm))
      .filter((own) => own.length > 1)
      .map((own) =>
        cells([`#${report.task.pr}`, own[0]!.arm, own.length, range(own.map(({ composite }) => composite)), range(own.map(({ angles }) => angles.architecture)), range(own.map(({ angles }) => angles.astra))]),
      ),
  );
  const body = lines.length > 0 ? [head, separator(head), ...lines].join("\n") : "_No task has repeated runs of an arm yet._";
  return ["## Spread over repeats", body].join("\n\n");
}

function taskSection({ report, rows }: TaskRows): string {
  const { task, scores, judgement, jev } = report;
  const header = `### [#${task.pr}](${task.url ?? `https://github.com/PostHog/posthog/pull/${task.pr}`}) ${task.title}`;
  const context = `Base \`${scores.baseCommit.slice(0, 11)}\`. Astra judge: ${judgement ? `\`${judgement.model}\`` : "not run yet"}. Jev: ${jev?.status === "graded" ? `\`${jev.model}\`` : jev ? `unavailable (${jev.reason})` : "not run yet"}.`;
  return [header, context, jevSkips(jev), architectureTable(rows), qualityTable(rows, report), processTable(rows), excerpts(rows)].filter(Boolean).join("\n\n");
}

function jevSkips(jev: JevReport | undefined): string {
  if (jev?.status !== "graded") return "";
  const skipped = Object.entries(jev.runs).flatMap(([run, grade]) => (grade.skipped ?? []).map(({ subject, reason }) => `- ${run}: \`${subject}\` (${reason})`));
  return skipped.length === 0 ? "" : ["Jev skipped these files as too large:", ...skipped].join("\n");
}

function architectureTable(rows: Row[]): string {
  const head = "| Run | Hygiene | Bypasses | New deps (undeclared) | Cycles | Unresolved | Files | Lines | Modules | Focus | Seams | Cohesion | Coupling | Fit | Overall |";
  const lines = rows.map(({ run, score, verdict }) => {
    const boundary = score.boundary;
    const focus = score.focus;
    const dependencies = boundary?.newCrossProductDependencies ?? [];
    return cells([
      run,
      score.hygiene ?? diffNote(score),
      boundary ? boundary.facadeBypasses.length : missing,
      boundary ? `${dependencies.length} (${dependencies.filter(({ declared }) => !declared).length})` : missing,
      boundary?.newCycles.length ?? missing,
      boundary?.newUnresolvedImports.length ?? missing,
      focus?.filesChanged ?? missing,
      focus ? focus.linesAdded + focus.linesRemoved : missing,
      focus?.modulesTouched ?? missing,
      score.focusScore ?? missing,
      verdict?.seams.score ?? missing,
      verdict?.cohesion.score ?? missing,
      verdict?.coupling.score ?? missing,
      verdict?.fit.score ?? missing,
      verdict?.overall.score ?? missing,
    ]);
  });
  return ["Architecture detail:", [head, separator(head), ...lines].join("\n")].join("\n\n");
}

function qualityTable(rows: Row[], { jev }: TaskReport): string {
  const head = "| Run | Changed functions | Max CC | Mean CC | CC > 10 | CC delta | Ruff | Duplicated % | Test / prod lines | Reference coverage | pytest | Jev file quality | py_compile failures |";
  const lines = rows.map(({ run, score }) => {
    const complexity = score.staticQuality && score.staticQuality.complexity !== "unavailable" ? score.staticQuality.complexity : undefined;
    const duplication = score.staticQuality && score.staticQuality.duplication !== "unavailable" ? score.staticQuality.duplication : undefined;
    const tests = score.tests;
    const grade = jev?.status === "graded" ? jev.runs[run] : undefined;
    return cells([
      run,
      complexity?.changedFunctions ?? missing,
      complexity?.maxCcn ?? missing,
      complexity?.meanCcn ?? missing,
      complexity?.overTen ?? missing,
      complexity?.ccnDelta ?? missing,
      score.build?.ruff.available ? score.build.ruff.violations.length : "unavailable",
      duplication?.percentage ?? missing,
      tests ? `${tests.testLinesAdded} / ${tests.productionLinesAdded}` : missing,
      tests?.referenceCoverage ?? missing,
      tests ? (tests.dynamic.status === "not run" ? `not run: ${tests.dynamic.reason}` : tests.dynamic.status) : missing,
      grade?.fileQuality ?? missing,
      score.build ? score.build.pyCompileFailures.length : missing,
    ]);
  });
  return ["Quality and tests detail:", [head, separator(head), ...lines].join("\n")].join("\n\n");
}

function processTable(rows: Row[]): string {
  const head = "| Run | Tool calls before first edit | Seconds before first edit | Architecture exploration before edit | Architecture reasoning before edit | Arch. tool calls | Turns | Wall (s) | Cost ($) |";
  const lines = rows.map(({ run, score }) => {
    const process = score.process;
    return cells([
      run,
      process?.toolCallsBeforeFirstEdit ?? missing,
      process?.secondsBeforeFirstEdit ?? missing,
      process?.architectureExplorationBeforeEdit ?? missing,
      process?.architectureReasoningBeforeEdit ?? missing,
      process?.architectureToolCalls ?? missing,
      process?.turns ?? missing,
      process?.wallSeconds ?? missing,
      process?.costUsd === null || process?.costUsd === undefined ? missing : process.costUsd.toFixed(2),
    ]);
  });
  return ["Process detail:", [head, separator(head), ...lines].join("\n")].join("\n\n");
}

function excerpts(rows: Row[]): string {
  const firsts = rows.filter(({ arm, score }, index) => score.process && rows.findIndex((row) => row.arm === arm) === index);
  if (firsts.length === 0) return "_No transcripts for this task._";
  return [
    "How the thinking differed before the first edit:",
    ...firsts.map(({ run, score }) => {
      const process = score.process!;
      const thought = process.firstArchitectureThought ? `first architecture thought: “${process.firstArchitectureThought}”` : "no architecture reasoning before it";
      return `- **${run}** made ${process.toolCallsBeforeFirstEdit} tool calls (${process.architectureExplorationBeforeEdit} architecture exploration) before its first edit; ${thought}`;
    }),
  ].join("\n");
}

function caveats(): string {
  return [
    "## Honesty caveats",
    "- Arm A had a human steering it over many turns, with review feedback; arms B and C get the task statement only. A–B differences conflate the model, the time, and the steering. B–C is the controlled comparison.",
    "- Replays are stochastic. Where the budget allowed, B and C ran more than once, and the spread above shows how far one run can be from another. With few tasks and few repeats, small differences are noise.",
    "- The Astra judge and Jev are models. The judge is one call per task; Jev is deterministic for the same input but still a model's opinion. Neither is ground truth.",
    "- The judge sees shuffled labels and runs from an empty directory, and its label key is written only after it answers, but its read-only sandbox can still read the disk; it is told the prompt holds everything it needs.",
    "- Boundary hygiene sees imports only. It does not see model access through `apps.get_model`, ORM traversal, or HTTP coupling, which `products/architecture.md` also governs.",
    "- Focus and intent alignment reward staying close to the smallest change and to the human's PR. Neither is always the right change.",
    "- Static quality and reference coverage are proxies: complexity is not design, and a test that names a function does not prove it tests it. `pytest` only runs where PostHog's services and Python environment exist.",
    "- No arm's diff is committed anywhere. PostHog stays untouched apart from scratch worktrees, which are removed after each run.",
  ].join("\n");
}

function consistencyCell(overlap: { modules: number; files: number } | null | undefined): string {
  return overlap ? `${overlap.modules} / ${overlap.files}` : missing;
}

function diffNote(score: ArmScore): string {
  return score.application === "empty" ? "no diff" : score.application === "failed" ? "diff did not apply" : missing;
}

function meanOf(values: (number | null)[]): string | number {
  const present = values.filter((value): value is number => value !== null);
  return present.length > 0 ? round(mean(present)) : missing;
}

function range(values: (number | null)[]): string {
  const present = values.filter((value): value is number => value !== null);
  return present.length > 0 ? `${Math.min(...present)}–${Math.max(...present)}` : missing;
}

function cells(values: (string | number)[]): string {
  return `| ${values.map((value) => String(value).replaceAll("|", "\\|").replaceAll("\n", " ")).join(" | ")} |`;
}

function separator(head: string): string {
  return `|${head.split("|").slice(1, -1).map(() => "---").join("|")}|`;
}
