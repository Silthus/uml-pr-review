import type { Subtype } from "../corrections/labels.ts";
import { subtypes } from "../corrections/labels.ts";
import { type Catchable, catchables, type GuardName, guardNames, judgmentKinds, type LintabilityLabel, ruleKinds, type Tool, tools } from "./labels.ts";
import type { FixStat } from "./sources.ts";

export const languages = ["TypeScript/JavaScript", "Python", "Rust", "other"] as const;
export type Language = (typeof languages)[number];

export type LabelledRow = LintabilityLabel & {
  pr: number;
  prUrl: string;
  commentUrl: string;
  path: string;
  language: Language;
  product: string;
  subtype: Subtype;
  quote: string;
  before: string;
  fix: string;
  fixStat: FixStat;
  failedGuards: GuardName[];
  rule: string | null;
};

export type LabelledTwice = { primary: LintabilityLabel; second: LintabilityLabel };

const firstSliceTools: Record<Language, readonly Tool[]> = {
  "TypeScript/JavaScript": ["oxlint", "eslint"],
  Python: ["tach", "import-linter", "ruff", "semgrep"],
  Rust: [],
  other: [],
};

const replayPreference = [/^products\/workflows\//, /^nodejs\/src\/cdp\//, /^frontend\/src\/scenes\/(hog-functions|workflows|messaging|data-pipelines)\//];
const replayCount = 5;
const topRuleCount = 10;

export function languageOf(path: string): Language {
  const extension = path.split(".").at(-1) ?? "";
  if (["ts", "tsx", "js", "jsx", "mjs", "cjs", "mts", "cts"].includes(extension)) return "TypeScript/JavaScript";
  if (extension === "py") return "Python";
  if (extension === "rs") return "Rust";
  return "other";
}

export function inFirstSlice(row: Pick<LabelledRow, "language" | "tool">): boolean {
  return firstSliceTools[row.language].includes(row.tool);
}

export function cohensKappa(pairs: [Catchable, Catchable][]): number {
  const observed = pairs.filter(([a, b]) => a === b).length / pairs.length;
  const expected = catchables.reduce((sum, value) => sum + (pairs.filter(([a]) => a === value).length / pairs.length) * (pairs.filter(([, b]) => b === value).length / pairs.length), 0);
  return expected === 1 ? 1 : (observed - expected) / (1 - expected);
}

export function report(rows: LabelledRow[], twice: LabelledTwice[]): string {
  return [
    "# Corpus coverage: which development corrections a manifest plus a linter could catch at write time",
    "",
    "Ticket [#110](https://github.com/Silthus/uml-pr-review/issues/110), part of map [#105](https://github.com/Silthus/uml-pr-review/issues/105). Generated by `bun benchmark/lintability/run.ts write` from the labels in `labels.jsonl` and `agreement.jsonl`; do not edit by hand.",
    "",
    "## Headline",
    "",
    ...headline(rows),
    "",
    "## Coverage by language",
    "",
    coverageTable("Language", languages, rows, (row) => row.language),
    "",
    "## Coverage by corpus sub-type",
    "",
    coverageTable("Sub-type", subtypes, rows, (row) => row.subtype),
    "",
    "## Coverage by rule kind",
    "",
    "Every correction gets exactly one kind. The six judgment kinds are never caught by construction.",
    "",
    coverageTable("Kind", ruleKinds, rows, (row) => row.ruleKind),
    "",
    "## Coverage by tool",
    "",
    coverageTable("Tool", tools, rows, (row) => row.tool),
    "",
    "## Which honesty guard failed",
    "",
    ...guardSection(rows),
    "",
    "## Top generalisable rules",
    "",
    ...topRules(rows),
    "",
    "## Agreement",
    "",
    ...agreementSection(twice),
    "",
    "## Replay candidates",
    "",
    ...replayCandidates(rows),
    "",
  ].join("\n");
}

function headline(rows: LabelledRow[]): string[] {
  const yes = rows.filter(({ catchable }) => catchable === "yes");
  const partial = rows.filter(({ catchable }) => catchable === "partial");
  const sliceLanguages = rows.filter(({ language }) => language === "TypeScript/JavaScript" || language === "Python");
  const slice = yes.filter(inFirstSlice);
  const slicePartial = partial.filter(inFirstSlice);
  return [
    `**${yes.length} of ${rows.length} development corrections (${percent(yes.length, rows.length)})** are catchable at write time, and ${partial.length} more (${percent(partial.length, rows.length)}) partly. Every other correction failed an honesty guard or is a judgment kind, and stays in review.`,
    "",
    `Through the tools of the first slice (TypeScript through oxlint \`jsPlugins\`, Python through \`tach\`, import-linter, ruff, and semgrep), the first slice catches **${slice.length} of ${rows.length} (${percent(slice.length, rows.length)})**, which is ${slice.length} of the ${sliceLanguages.length} TypeScript and Python corrections (${percent(slice.length, sliceLanguages.length)}); ${slicePartial.length} more are partly caught.`,
  ];
}

function coverageTable<K extends string>(title: string, keys: readonly K[], rows: LabelledRow[], keyOf: (row: LabelledRow) => K): string {
  const lines = keys.flatMap((key) => {
    const group = rows.filter((row) => keyOf(row) === key);
    if (group.length === 0) return [];
    const yes = group.filter(({ catchable }) => catchable === "yes").length;
    const partial = group.filter(({ catchable }) => catchable === "partial").length;
    return [`| ${key} | ${group.length} | ${yes} | ${partial} | ${percent(yes, group.length)} |`];
  });
  return [`| ${title} | Corrections | Yes | Partial | Yes share |`, "| --- | --- | --- | --- | --- |", ...lines].join("\n");
}

function guardSection(rows: LabelledRow[]): string[] {
  const rejected = rows.filter(({ catchable }) => catchable === "no");
  const judgmentOnly = rejected.filter(({ failedGuards, ruleKind }) => failedGuards.length === 0 && (judgmentKinds as readonly string[]).includes(ruleKind));
  return [
    `Of the ${rejected.length} corrections that stay in review, this is how often each guard failed (a correction can fail several). ${judgmentOnly.length} failed no guard but are a judgment kind with no candidate rule.`,
    "",
    "| Guard | Failed |",
    "| --- | --- |",
    ...guardNames.map((name) => `| ${name} | ${rejected.filter(({ failedGuards }) => failedGuards.includes(name)).length} |`),
  ];
}

function topRules(rows: LabelledRow[]): string[] {
  const groups = Map.groupBy(
    rows.filter((row) => row.rule !== null),
    (row) => row.rule!,
  );
  const ranked = [...groups.entries()]
    .map(([rule, members]) => ({ rule, yes: members.filter(({ catchable }) => catchable === "yes").length, partial: members.filter(({ catchable }) => catchable === "partial").length, tools: [...new Set(members.map(({ tool }) => tool))].sort().join(", ") }))
    .sort((a, b) => b.yes - a.yes || b.partial - a.partial || a.rule.localeCompare(b.rule))
    .slice(0, topRuleCount);
  return ["Caught corrections grouped by the general rule that catches them, ranked by full catches.", "", "| # | Rule | Yes | Partial | Tools |", "| --- | --- | --- | --- | --- |", ...ranked.map(({ rule, yes, partial, tools }, index) => `| ${index + 1} | ${rule} | ${yes} | ${partial} | ${tools} |`)];
}

function agreementSection(twice: LabelledTwice[]): string[] {
  if (twice.length === 0) return ["No correction was labelled twice."];
  const pairs = twice.map(({ primary, second }): [Catchable, Catchable] => [primary.catchable, second.catchable]);
  const agreed = pairs.filter(([a, b]) => a === b).length;
  const sameKind = twice.filter(({ primary, second }) => primary.ruleKind === second.ruleKind).length;
  return [
    `Cohen's kappa on \`catchable\` is **${cohensKappa(pairs).toFixed(2)}** over ${pairs.length} rows (raw agreement ${percent(agreed, pairs.length)}). The two labellers chose the same rule kind for ${sameKind} of ${pairs.length} (${percent(sameKind, pairs.length)}).`,
    "",
    "| Primary \\ second | yes | partial | no |",
    "| --- | --- | --- | --- |",
    ...catchables.map((a) => `| ${a} | ${catchables.map((b) => pairs.filter(([x, y]) => x === a && y === b).length).join(" | ")} |`),
  ];
}

function replayCandidates(rows: LabelledRow[]): string[] {
  const section = (language: Language) => {
    const picked = rows
      .filter((row) => row.language === language && row.catchable === "yes")
      .toSorted((a, b) => preference(a.path) - preference(b.path) || size(a.fixStat) - size(b.fixStat) || a.pr - b.pr)
      .slice(0, replayCount);
    return [
      `### ${language}`,
      "",
      "| PR | File | Correction | `before` | Rule sketch | Fix size |",
      "| --- | --- | --- | --- | --- | --- |",
      ...picked.map((row) => `| [#${row.pr}](${row.prUrl}) | \`${row.path}\` | [${cell(row.quote)}](${row.commentUrl}) | \`${row.before}\` | ${cell(row.ruleSketch)} | ${row.fixStat.files} files, +${row.fixStat.added}/−${row.fixStat.removed} |`),
    ];
  };
  return ["Caught corrections, preferring `products/workflows`, `nodejs/src/cdp`, and the hog-functions and workflows scenes, then the smallest fix commit, which is the most self-contained replay.", "", ...section("TypeScript/JavaScript"), "", ...section("Python")];
}

function preference(path: string): number {
  const index = replayPreference.findIndex((pattern) => pattern.test(path));
  return index === -1 ? replayPreference.length : index;
}

function size({ added, removed }: FixStat): number {
  return added + removed;
}

function cell(text: string): string {
  return text.replaceAll("|", "\\|").replaceAll("\n", " ");
}

function percent(part: number, whole: number): string {
  return whole === 0 ? "n/a" : `${((part / whole) * 100).toFixed(1)}%`;
}
